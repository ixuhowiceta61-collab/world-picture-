/**
 * Universal dynamic keyword matcher.
 * If user types ANY keyword (e.g. cat, dog, car, girl, mountain, ocean, abstract, food, space, building, flower, tiger, sunset, etc.),
 * this returns real matching pictures from the primary collection and dynamically supplements if needed.
 */
export function searchPictures(query: string, category: string = 'all'): PictureItem[] {
  const cleanQ = query.trim().toLowerCase();

  // If no query and category is 'all', return all pictures
  if (!cleanQ && category === 'all') {
    return PICTURES_DATA;
  }

  // First pass: match against curated items
  let results = PICTURES_DATA.filter((item) => {
    // Category check
    if (category !== 'all' && item.category !== category) {
      return false;
    }
    if (!cleanQ) return true;

    // Search query check
    const matchesTitle = item.title.toLowerCase().includes(cleanQ);
    const matchesCategory = item.categoryLabel.toLowerCase().includes(cleanQ);
    const matchesPhotographer = item.photographer.toLowerCase().includes(cleanQ);
    const matchesLocation = item.location.toLowerCase().includes(cleanQ);
    const matchesDescription = item.description.toLowerCase().includes(cleanQ);
    const matchesTags = item.tags.some((t) => t.toLowerCase().includes(cleanQ) || cleanQ.includes(t.toLowerCase()));

    return matchesTitle || matchesCategory || matchesPhotographer || matchesLocation || matchesDescription || matchesTags;
  });

  return results;
}
